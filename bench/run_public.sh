# Public VLM benchmarks on desktop: one llama-server per model, driven by lmms-eval.
# Cycles the models one at a time: start server -> run tasks -> stop server.
#
# Usage (from the repo root, Git Bash):
#   bench/run_public.sh [-m "model1 model2"] [-t "task1,task2"] [-l LIMIT] [-o OUT_DIR]
#
# Defaults: all models in MODELS below, all agreed public tasks, no limit, $EVAL_DIR/results/public.
# Setup (once): bench/setup_eval.sh

set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
# Settings from .env (written by setup-config.sh / setup-config.ps1); a value the caller already set wins
ENV_FILE="$ROOT/.env"
if [ -f "$ENV_FILE" ]; then
  while IFS='=' read -r k v || [ -n "$k" ]; do
    v="${v%$'\r'}"
    [[ $k =~ ^[A-Z_][A-Z0-9_]*$ ]] && [ -z "${!k:-}" ] && export "$k=$v"
  done < "$ENV_FILE"
fi
need() { for k; do [ -n "${!k:-}" ] || { echo "$k is not set: run setup-config.sh (it writes .env)"; exit 1; }; done; }
need LLAMA_SERVER MODEL_DIR EVAL_DIR
EVAL="$EVAL_DIR"   # generated by bench/setup_eval.sh (venvs, authors' code, data, logs, results)

# First run on this machine: set up $EVAL once (setup_eval writes the stamp only when every step succeeded)
if [ ! -f "$EVAL/.setup_done" ]; then
  echo "$EVAL is not set up yet: running bench/setup_eval.sh (one time)"
  bash bench/setup_eval.sh || exit 1
fi

PY="${PY:-$EVAL/.venv/Scripts/python}"
[ -x "$PY" ] || PY="$EVAL/.venv/bin/python"
PORT="${PORT:-8081}"
CTX="${CTX:-32768}"
SLOTS="${SLOTS:-4}"

TASKS="ocrbench,mmstar,chartqa,docvqa_val,textvqa_val,mmmu_val,pope"
LIMIT=""
OUT="$EVAL/results/public"
SEL=""

while getopts "m:t:l:o:" opt; do
  case $opt in
    m) SEL="$OPTARG" ;;
    t) TASKS="$OPTARG" ;;
    l) LIMIT="$OPTARG" ;;
    o) OUT="$OPTARG" ;;
    *) echo "bad option"; exit 1 ;;
  esac
done

# name | model args for llama-server (paths relative to MODEL_DIR, or -hf repo:quant)
declare -A MODELS=(
  [qwen35_0.8b]="-m $MODEL_DIR/Qwen3.5-VL-0.8B-Unsloth/Qwen3.5-0.8B-Q4_K_M.gguf --mmproj $MODEL_DIR/Qwen3.5-VL-0.8B-Unsloth/mmproj-F16.gguf"
  [qwen38_2b]="-m $MODEL_DIR/Qwen3.8-2B/Qwen3.8-2B-Distill-heretic.Q4_K_M.gguf --mmproj $MODEL_DIR/Qwen3.8-2B/Qwen3.8-2B-Distill-heretic.mmproj-f16.gguf"
  [qwen35_2b]="-m $MODEL_DIR/Qwen3.5-VL-2B-Unsloth/Qwen3.5-2B-Q4_K_M.gguf --mmproj $MODEL_DIR/Qwen3.5-VL-2B-Unsloth/mmproj-F16.gguf"
  [qwen3vl_2b]="-m $MODEL_DIR/Qwen3-VL-2B-Unsloth/Qwen3-VL-2B-Instruct-Q4_K_M.gguf --mmproj $MODEL_DIR/Qwen3-VL-2B-Unsloth/mmproj-F16.gguf"
  [qwen2vl_2b]="-m $MODEL_DIR/Qwen2-VL-2B-Bartowski/Qwen2-VL-2B-Instruct-Q4_K_M.gguf --mmproj $MODEL_DIR/Qwen2-VL-2B-Bartowski/mmproj-Qwen2-VL-2B-Instruct-f16.gguf"
  [qwen35_4b]="-m $MODEL_DIR/Qwen3.5-4B/Qwen3.5-4B-Q4_K_M.gguf --mmproj $MODEL_DIR/Qwen3.5-4B/mmproj-f16.gguf"
  [lfm25_1.6b]="-m $MODEL_DIR/LFM2.5-VL-1.6B/LFM2.5-VL-1.6B-Q4_K_M.gguf --mmproj $MODEL_DIR/LFM2.5-VL-1.6B/mmproj-LFM2.5-VL-1.6B-F16.gguf"
  [smolvlm2_2.2b]="-m $MODEL_DIR/SmolVLM2-2.2B/SmolVLM2-2.2B-Instruct-Q4_K_M.gguf --mmproj $MODEL_DIR/SmolVLM2-2.2B/mmproj-SmolVLM2-2.2B-Instruct-f16.gguf"
  [granite32_2b]="-m $MODEL_DIR/GraniteVision3.2-2B/granite-vision-3.2-2b-Q4_K_M.gguf --mmproj $MODEL_DIR/GraniteVision3.2-2B/mmproj-model-f16.gguf"
  # Reference row (plan: official Qwen3.5-2B at BF16); downloaded on first use
  [qwen35_2b_bf16]="-hf unsloth/Qwen3.5-2B-GGUF:BF16"
)
ORDER="qwen35_0.8b qwen38_2b qwen35_2b qwen3vl_2b qwen2vl_2b qwen35_4b lfm25_1.6b smolvlm2_2.2b granite32_2b"
[ -n "$SEL" ] && ORDER="$SEL"

mkdir -p $EVAL/logs "$OUT"
SERVER_PID=""

stop_server() {
  if [ -n "$SERVER_PID" ] && kill -0 "$SERVER_PID" 2>/dev/null; then
    kill "$SERVER_PID" 2>/dev/null
    for _ in $(seq 1 30); do kill -0 "$SERVER_PID" 2>/dev/null || break; sleep 1; done
  fi
  SERVER_PID=""
}
trap stop_server EXIT INT TERM

# Replace any HF token lmms-eval wrote into the results files
redact_token() {
  find "$OUT" -name "*_results.json" -print0 2>/dev/null \
    | xargs -0 -r sed -i -E 's/hf_[A-Za-z0-9]{20,}/hf_REDACTED/g'
}

fail=0   # set when a model's run fails; the loop goes on to the next model
for name in $ORDER; do
  args="${MODELS[$name]:-}"
  if [ -z "$args" ]; then echo "unknown model: $name"; fail=1; continue; fi

  if curl -s --max-time 2 "http://127.0.0.1:$PORT/health" >/dev/null 2>&1; then
    echo "port $PORT is already in use; stop that server first"; exit 1
  fi

  log="$EVAL/logs/server_${name}.log"
  echo "=== $name: starting server"
  # Thinking off (Qwen3.5/3.8 templates read enable_thinking; other templates ignore it). Greedy comes from lmms-eval.
  # shellcheck disable=SC2086
  "$LLAMA_SERVER" $args -c "$CTX" -np "$SLOTS" -ngl 99 --jinja \
    --reasoning off \
    --host 127.0.0.1 --port "$PORT" > "$log" 2>&1 &
  SERVER_PID=$!

  ok=0
  for _ in $(seq 1 300); do
    if curl -s --max-time 2 "http://127.0.0.1:$PORT/health" | grep -q '"ok"'; then ok=1; break; fi
    kill -0 "$SERVER_PID" 2>/dev/null || break
    sleep 2
  done
  if [ $ok -ne 1 ]; then echo "=== $name: server not ready, see $log"; fail=1; stop_server; continue; fi

  echo "=== $name: running $TASKS"
  limit_arg=()
  [ -n "$LIMIT" ] && limit_arg=(--limit "$LIMIT")
  # The task configs need an HF token (token: True). lmms-eval also copies HF_TOKEN into results.json,
  # so redact_token runs after every model (and *_results.json is gitignored).
  env PYTHONUTF8=1 PYTHONIOENCODING=utf-8 "$PY" -m lmms_eval \
    --model openai \
    --model_args "model_version=$name,base_url=http://127.0.0.1:$PORT/v1,api_key=EMPTY" \
    --tasks "$TASKS" --batch_size 1 --log_samples \
    --output_path "$OUT" "${limit_arg[@]}" 2>&1 | tee "$EVAL/logs/lmms_${name}.log" | grep -E "^\||Final Score|ERROR|Traceback"
  [ "${PIPESTATUS[0]}" -eq 0 ] || { echo "=== $name: lmms-eval failed, see $EVAL/logs/lmms_${name}.log"; fail=1; }

  stop_server
  redact_token
  echo "=== $name: done"
done
exit $fail
