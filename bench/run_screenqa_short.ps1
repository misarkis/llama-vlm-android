# =============================================================================
# run_screenqa_short.ps1
# =============================================================================
# ScreenQA-Short (test split) on desktop: questions/answers from Google's official release
# (google-research-datasets/screen_qa), scored with Google's official metric code.
# One llama-server per model, cycled one at a time.
# PowerShell version of bench/run_screenqa_short.sh (same models, settings and outputs).
#
# SETTINGS (.env, written by setup-config.ps1): LLAMA_SERVER, MODEL_DIR, EVAL_DIR
# SETUP (once): bench\setup_eval.ps1
#   Screenshots are downloaded on first run from bevaya/RICO-ScreenQA-Short (CC-BY-4.0)
#   into $EVAL_DIR\data\ScreenQA-Short\.
#
# USAGE (from anywhere):
#   .\bench\run_screenqa_short.ps1 [-Models "model1 model2"] [-Out DIR] [-Limit N]
# =============================================================================

param(
    [string]$Models = "",
    [string]$Out = "",
    [int]$Limit = 0
)

. (Join-Path $PSScriptRoot "bench_common.ps1")
Assert-Settings @("LLAMA_SERVER", "MODEL_DIR", "EVAL_DIR")

$Eval = $env:EVAL_DIR   # generated by bench\setup_eval.ps1 (venvs, authors' code, data, logs, results)

# First run on this machine: set up $Eval once (setup_eval writes the stamp only when every step succeeded)
if (-not (Test-Path "$Eval\.setup_done")) {
    Write-Host "$Eval is not set up yet: running bench\setup_eval.ps1 (one time)"
    & (Join-Path $PSScriptRoot "setup_eval.ps1")
    if (-not (Test-Path "$Eval\.setup_done")) { Write-Host "setup_eval did not finish" -ForegroundColor Red; exit 1 }
}
$Py = if ($env:PY) { $env:PY } else { Get-VenvPython "$Eval\.venv" }
$Port = if ($env:PORT) { [int]$env:PORT } else { 8081 }
$Ctx = if ($env:CTX) { [int]$env:CTX } else { 32768 }
$Slots = if ($env:SLOTS) { [int]$env:SLOTS } else { 4 }
if (-not $Out) { $Out = "$Eval\results\screenqa_short" }
$Order = if ($Models) { $Models } else { $DefaultOrder }
$ModelTable = Get-BenchModels

New-Item -ItemType Directory -Force -Path "$Eval\logs", $Out | Out-Null

$env:PYTHONUTF8 = "1"; $env:PYTHONIOENCODING = "utf-8"
$server = $null
$fail = $false   # set when a model's run fails; the loop goes on to the next model
try {
    foreach ($name in ($Order -split '\s+' | Where-Object { $_ })) {
        if (-not $ModelTable.Contains($name)) { Write-Host "unknown model: $name"; $fail = $true; continue }
        if (Test-PortInUse $Port) { Write-Host "port $Port is already in use; stop that server first"; exit 1 }

        $log = "$Eval\logs\server_sqa_$name.log"
        Write-Host "=== ${name}: starting server"
        $server = Start-BenchServer -ModelArgs $ModelTable[$name] -Port $Port -Ctx $Ctx -Slots $Slots -Log $log
        if (-not $server) { Write-Host "=== ${name}: server not ready, see $log"; $fail = $true; continue }

        Write-Host "=== ${name}: running ScreenQA-Short"
        & $Py bench\run_screenqa_short.py --model $name --port $Port `
            --workers $Slots --limit $Limit --out $Out 2>&1 |
            ForEach-Object { "$_" } |
            Tee-Object -FilePath "$Eval\logs\sqa_$name.log"
        if ($LASTEXITCODE -ne 0) { Write-Host "=== ${name}: ScreenQA client failed, see $Eval\logs\sqa_$name.log"; $fail = $true }

        Stop-BenchServer $server; $server = $null
        Write-Host "=== ${name}: done"
    }
} finally {
    Stop-BenchServer $server
}
if ($fail) { exit 1 }
