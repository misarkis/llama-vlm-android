# =============================================================================
# run_public.ps1
# =============================================================================
# Public VLM benchmarks on desktop: one llama-server per model, driven by lmms-eval.
# Cycles the models one at a time: start server -> run tasks -> stop server.
# PowerShell version of bench/run_public.sh (same models, tasks, settings and outputs).
#
# SETTINGS (.env, written by setup-config.ps1): LLAMA_SERVER, MODEL_DIR, EVAL_DIR
# SETUP (once): bench\setup_eval.ps1
#
# USAGE (from anywhere):
#   .\bench\run_public.ps1 [-Models "model1 model2"] [-Tasks "task1,task2"] [-Limit N] [-Out DIR]
#
# Defaults: all models, all agreed public tasks, no limit, $EVAL_DIR\results\public.
# The task configs need a Hugging Face token in $env:HF_TOKEN (gated datasets).
# =============================================================================

param(
    [string]$Models = "",
    [string]$Tasks = "ocrbench,mmstar,chartqa,docvqa_val,textvqa_val,mmmu_val,pope",
    [string]$Limit = "",
    [string]$Out = ""
)

. (Join-Path $PSScriptRoot "bench_common.ps1")
Assert-Settings @("LLAMA_SERVER", "MODEL_DIR", "EVAL_DIR")

$Eval = $env:EVAL_DIR   # generated by bench\setup_eval.ps1 (venvs, authors' code, data, logs, results)

# First run on this machine: set up $Eval once (setup_eval writes the stamp only when every step succeeded)
if (-not (Test-Path "$Eval\.setup_done")) {
    Write-Host "$Eval is not set up yet: running bench\setup_eval.ps1 (one time)"
    & (Join-Path $PSScriptRoot "setup_eval.ps1")
    if (-not (Test-Path "$Eval\.setup_done")) { Write-Host "setup_eval did not finish" -ForegroundColor Red; exit 1 }
}
$Py = if ($env:PY) { $env:PY } else { Get-VenvPython "$Eval\.venv" }
$Port = if ($env:PORT) { [int]$env:PORT } else { 8081 }
$Ctx = if ($env:CTX) { [int]$env:CTX } else { 32768 }
$Slots = if ($env:SLOTS) { [int]$env:SLOTS } else { 4 }
if (-not $Out) { $Out = "$Eval\results\public" }
$Order = if ($Models) { $Models } else { $DefaultOrder }
$ModelTable = Get-BenchModels

New-Item -ItemType Directory -Force -Path "$Eval\logs", $Out | Out-Null

# Replace any HF token lmms-eval wrote into the results files
function Remove-HfToken {
    Get-ChildItem -Path $Out -Recurse -Filter "*_results.json" -ErrorAction SilentlyContinue | ForEach-Object {
        $text = [IO.File]::ReadAllText($_.FullName)
        $clean = $text -replace 'hf_[A-Za-z0-9]{20,}', 'hf_REDACTED'
        if ($clean -ne $text) { [IO.File]::WriteAllText($_.FullName, $clean) }
    }
}

$env:PYTHONUTF8 = "1"; $env:PYTHONIOENCODING = "utf-8"
$server = $null
$fail = $false   # set when a model's run fails; the loop goes on to the next model
try {
    foreach ($name in ($Order -split '\s+' | Where-Object { $_ })) {
        if (-not $ModelTable.Contains($name)) { Write-Host "unknown model: $name"; $fail = $true; continue }
        if (Test-PortInUse $Port) { Write-Host "port $Port is already in use; stop that server first"; exit 1 }

        $log = "$Eval\logs\server_$name.log"
        Write-Host "=== ${name}: starting server"
        $server = Start-BenchServer -ModelArgs $ModelTable[$name] -Port $Port -Ctx $Ctx -Slots $Slots -Log $log
        if (-not $server) { Write-Host "=== ${name}: server not ready, see $log"; $fail = $true; continue }

        Write-Host "=== ${name}: running $Tasks"
        $limitArg = if ($Limit) { @("--limit", $Limit) } else { @() }
        # lmms-eval also copies HF_TOKEN into results.json, so Remove-HfToken runs after every model
        & $Py -m lmms_eval --model openai `
            --model_args "model_version=$name,base_url=http://127.0.0.1:$Port/v1,api_key=EMPTY" `
            --tasks $Tasks --batch_size 1 --log_samples --output_path $Out @limitArg 2>&1 |
            ForEach-Object { "$_" } |
            Tee-Object -FilePath "$Eval\logs\lmms_$name.log" |
            Select-String -Pattern '^\||Final Score|ERROR|Traceback' | ForEach-Object { $_.Line }
        if ($LASTEXITCODE -ne 0) { Write-Host "=== ${name}: lmms-eval failed, see $Eval\logs\lmms_$name.log"; $fail = $true }

        Stop-BenchServer $server; $server = $null
        Remove-HfToken
        Write-Host "=== ${name}: done"
    }
} finally {
    Stop-BenchServer $server
}
if ($fail) { exit 1 }
