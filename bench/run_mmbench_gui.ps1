# =============================================================================
# run_mmbench_gui.ps1
# =============================================================================
# MMBench-GUI L1 (GUI content understanding) on desktop with the authors' official code
# (open-compass/MMBench-GUI on VLMEvalKit). One llama-server per model, cycled one at a time.
# PowerShell version of bench/run_mmbench_gui.sh (same models, settings and outputs).
#
# SETTINGS (.env, written by setup-config.ps1): LLAMA_SERVER, MODEL_DIR, EVAL_DIR
# SETUP (once): bench\setup_eval.ps1 -MmbenchGui
#   (VLMEvalKit at the authors' pin, CPU torch, OpenGVLab/MMBench-GUI L1 data in $EVAL_DIR\data\LMUData\MMBench-GUI\)
#
# USAGE (from anywhere):
#   .\bench\run_mmbench_gui.ps1 [-Models "model1 model2"] [-Out DIR]
#   $env:LMU_DIR = "$EVAL_DIR\data\LMUData_gui198" runs a subset folder laid out like the full one
#   (the phone subset: every 18th screenshot of L1_annotations.json, 198 questions); default the full L1.
#
# Config: bench\configs\mmbench_gui_l1.json (official L1 prompt and exact-match scoring; greedy decoding).
# =============================================================================

param(
    [string]$Models = "",
    [string]$Out = ""
)

. (Join-Path $PSScriptRoot "bench_common.ps1")
Assert-Settings @("LLAMA_SERVER", "MODEL_DIR", "EVAL_DIR")

$Eval = $env:EVAL_DIR   # generated by bench\setup_eval.ps1 (venvs, authors' code, data, logs, results)

# First run on this machine: set up $Eval once (setup_eval writes the stamp only when every step succeeded)
if (-not (Test-Path "$Eval\.setup_mmbench_gui_done")) {
    Write-Host "$Eval is not set up yet: running bench\setup_eval.ps1 -MmbenchGui (one time)"
    & (Join-Path $PSScriptRoot "setup_eval.ps1") -MmbenchGui
    if (-not (Test-Path "$Eval\.setup_mmbench_gui_done")) { Write-Host "setup_eval did not finish" -ForegroundColor Red; exit 1 }
}
$Py = if ($env:PY) { $env:PY } else { Get-VenvPython "$Eval\.venv-vlmeval" }
$BenchDir = (Resolve-Path "$Eval\third_party\MMBench-GUI").Path
$Port = if ($env:PORT) { [int]$env:PORT } else { 8081 }
$Ctx = if ($env:CTX) { [int]$env:CTX } else { 32768 }
$Slots = if ($env:SLOTS) { [int]$env:SLOTS } else { 4 }
if (-not $Out) { $Out = "$Eval\results\mmbench_gui" }
$Order = if ($Models) { $Models } else { $DefaultOrder }
$ModelTable = Get-BenchModels

New-Item -ItemType Directory -Force -Path "$Eval\logs", "$Out\configs" | Out-Null
$LmuSrc = if ($env:LMU_DIR) { ConvertTo-WindowsPath $env:LMU_DIR } else { "$Eval\data\LMUData" }
$Lmu = (Resolve-Path $LmuSrc).Path
$OutAbs = (Resolve-Path $Out).Path
$LogDir = (Resolve-Path "$Eval\logs").Path   # the run below changes directory

$env:PYTHONUTF8 = "1"; $env:PYTHONIOENCODING = "utf-8"
$server = $null
$fail = $false   # set when a model's run fails; the loop goes on to the next model
try {
    foreach ($name in ($Order -split '\s+' | Where-Object { $_ })) {
        if (-not $ModelTable.Contains($name)) { Write-Host "unknown model: $name"; $fail = $true; continue }
        if (Test-PortInUse $Port) { Write-Host "port $Port is already in use; stop that server first"; exit 1 }

        $log = "$Eval\logs\server_gui_$name.log"
        Write-Host "=== ${name}: starting server"
        $server = Start-BenchServer -ModelArgs $ModelTable[$name] -Port $Port -Ctx $Ctx -Slots $Slots -Log $log
        if (-not $server) { Write-Host "=== ${name}: server not ready, see $log"; $fail = $true; continue }

        $cfg = "$OutAbs\configs\$name.json"
        (Get-Content "bench\configs\mmbench_gui_l1.json" -Raw) -replace '__MODEL__', $name -replace '__PORT__', "$Port" |
            Set-Content -Path $cfg -NoNewline -Encoding utf8NoBOM

        # The authors' .env sets EVAL_WORK_DIR=./evaluation_results, which overrides --work-dir, and VLMEvalKit
        # reuses a prediction file it finds there from the same day instead of asking the model again.
        # So each run starts with no results folder for this model, and its results are moved to $Out after.
        $res = "$BenchDir\evaluation_results\$name"
        if (Test-Path $res) { Move-Item $res "$res.prev_$(Get-Date -Format yyyyMMdd_HHmmss)" }

        Write-Host "=== ${name}: running MMBench-GUI L1"
        $env:LMUData = $Lmu
        Push-Location $BenchDir
        try {
            & $Py evaluate.py --config $cfg --work-dir $OutAbs --api-nproc $Slots 2>&1 |
                ForEach-Object { "$_" } |
                Tee-Object -FilePath "$LogDir\gui_$name.log" |
                Select-String -Pattern 'Evaluation Results|overall|Overall|ERROR|Traceback' | ForEach-Object { $_.Line }
        } finally {
            Pop-Location
        }

        if (Test-Path $res) {
            New-Item -ItemType Directory -Force -Path "$Out\$name" | Out-Null
            Get-ChildItem $res | Move-Item -Destination "$Out\$name"
            Remove-Item $res
        } else {
            Write-Host "=== ${name}: no MMBench-GUI results, see $LogDir\gui_$name.log"; $fail = $true
        }

        Stop-BenchServer $server; $server = $null
        Write-Host "=== ${name}: done"
    }
} finally {
    Stop-BenchServer $server
}
if ($fail) { exit 1 }
